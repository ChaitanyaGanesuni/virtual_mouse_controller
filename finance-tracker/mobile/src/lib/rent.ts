import { inr } from './analysis';
import { financialYear } from './tax';
import type { Transaction } from './types';

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

export interface RentMonth {
  month: string; // YYYY-MM
  label: string; // "April 2026"
  amount: number;
  paidOn: number;
  landlord: string;
  mode: string;
  txnIds: string[];
}

/** Rent paid in the financial year, one row per month (several payments in a month are combined). */
export function rentPayments(txns: Transaction[], now = Date.now()): RentMonth[] {
  const { start, end } = financialYear(now);
  const map = new Map<string, RentMonth>();
  for (const t of txns) {
    if (t.direction !== 'debit' || t.category !== 'Rent & Housing' || t.date < start || t.date > end) continue;
    const d = new Date(t.date);
    const k = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
    const r = map.get(k) ?? { month: k, label: `${MONTHS[d.getMonth()]} ${d.getFullYear()}`, amount: 0, paidOn: t.date, landlord: t.merchant, mode: t.mode, txnIds: [] };
    r.amount += t.amount;
    r.paidOn = Math.max(r.paidOn, t.date);
    r.txnIds.push(t.id);
    if (!r.landlord && t.merchant) r.landlord = t.merchant;
    map.set(k, r);
  }
  return [...map.values()].sort((a, b) => a.month.localeCompare(b.month));
}

export interface RentProfile {
  tenant: string;
  landlord: string;
  landlordPan: string;
  address: string;
}

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

/** Printable HTML (one receipt per page) for HRA claims. */
export function rentReceiptsHtml(p: RentProfile, months: RentMonth[], now = Date.now()): string {
  const total = months.reduce((s, m) => s + m.amount, 0);
  const fy = financialYear(now).label;
  const panNeeded = total > 100_000;
  const page = (m: RentMonth, i: number) => `
  <section class="r">
    <div class="h"><div><div class="t">RENT RECEIPT</div><div class="s">${esc(fy)} · No. ${i + 1}</div></div><div class="amt">${esc(inr(m.amount))}</div></div>
    <p>Received a sum of <b>${esc(inr(m.amount))}</b> from <b>${esc(p.tenant || '________________')}</b>
    towards rent for the month of <b>${esc(m.label)}</b> for the property at
    <b>${esc(p.address || '________________________________')}</b>.</p>
    <table>
      <tr><td>Paid on</td><td>${new Date(m.paidOn).toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' })}</td></tr>
      <tr><td>Mode of payment</td><td>${esc(m.mode === 'OTHER' ? 'Bank transfer' : m.mode)}</td></tr>
      <tr><td>Landlord</td><td>${esc(p.landlord || m.landlord || '________________')}</td></tr>
      <tr><td>Landlord PAN</td><td>${esc(p.landlordPan || (panNeeded ? '__________ (required: annual rent above ₹1,00,000)' : 'Not required'))}</td></tr>
    </table>
    <div class="sig"><div>Signature of landlord</div></div>
  </section>`;
  return `<!doctype html><html><head><meta charset="utf-8"><style>
  body{font-family:-apple-system,Roboto,Helvetica,Arial,sans-serif;color:#111;margin:0}
  .r{page-break-after:always;padding:48px 44px;border:1px solid #ddd;margin:24px;border-radius:12px}
  .h{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:2px solid #0F9F74;padding-bottom:12px;margin-bottom:18px}
  .t{font-size:22px;font-weight:800;letter-spacing:2px;color:#0F9F74}.s{color:#666;font-size:12px;margin-top:4px}
  .amt{font-size:26px;font-weight:800}p{font-size:15px;line-height:1.7}
  table{width:100%;border-collapse:collapse;margin-top:16px;font-size:14px}td{padding:8px 0;border-bottom:1px solid #eee}td:first-child{color:#666;width:40%}
  .sig{margin-top:70px;display:flex;justify-content:flex-end}.sig div{border-top:1px solid #333;padding-top:6px;width:220px;text-align:center;font-size:13px;color:#444}
  .sum{margin:24px;padding:20px 44px;font-size:14px;color:#444}
  </style></head><body>
  ${months.map(page).join('')}
  <div class="sum">Total rent ${esc(fy)}: <b>${esc(inr(total))}</b> across ${months.length} month(s). Generated by Paisa Watch from your bank alerts. Receipts must be signed by the landlord.</div>
  </body></html>`;
}
